"""
2-4. Name Cases: Use a variable to represent a person’s name, and then
print that person’s name in lowercase, uppercase, and title case
"""

person_name = "aayush thakkar"
# Title case
message = f"Hello {person_name.title()}, would you like to learn some Python today?"
# upper case
message = f"Hello {person_name.upper()}, would you like to learn some Python today?"
# lower case
message = f"Hello {person_name.lower()}, would you like to learn some Python today?"
